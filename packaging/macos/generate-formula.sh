#!/usr/bin/env bash
# generate-formula.sh — Homebrew formula for the UFOP CLI from a release
# tarball made by packaging/linux/package-cli.sh (universal-apple-darwin).
#
# The formula installs bin/ufop (and bin/ufop-server when packaged), the
# bash / zsh / fish completions and the man pages from the tarball, so
# `brew install` gives completions without running the binary.
#
# Usage:
#   packaging/macos/generate-formula.sh --version 1.2.0 \
#       --url https://github.com/ClappeDiya/file-manager/releases/download/v1.2.0/ufop-1.2.0-universal-apple-darwin.tar.gz \
#       --sha256 <hex> [--out ufop.rb]
#
# Publish by committing the file to the tap (ClappeDiya/homebrew-tap,
# Formula/ufop.rb); release-local.sh uploads it with the release.

set -euo pipefail

VERSION=""
URL=""
SHA=""
OUT=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --version) VERSION="$2"; shift 2 ;;
    --url) URL="$2"; shift 2 ;;
    --sha256) SHA="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help) sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "generate-formula: unknown argument: $1" >&2; exit 2 ;;
  esac
done
[[ -n "$VERSION" && -n "$URL" && -n "$SHA" ]] || { echo "generate-formula: --version, --url and --sha256 are required" >&2; exit 2; }
[[ "$SHA" =~ ^[0-9a-f]{64}$ ]] || { echo "generate-formula: --sha256 must be 64 lowercase hex digits" >&2; exit 2; }

formula() {
  cat <<RUBY
# Generated by packaging/macos/generate-formula.sh for ufop ${VERSION}.
class Ufop < Formula
  desc "UFOP command-line tools: versioned encrypted backups, copy, sync, transfers"
  homepage "https://github.com/ClappeDiya/file-manager"
  url "${URL}"
  sha256 "${SHA}"
  version "${VERSION}"
  license :cannot_represent

  def install
    bin.install "bin/ufop"
    bin.install "bin/ufop-server" if File.exist?("bin/ufop-server")
    bash_completion.install Dir["share/bash-completion/completions/*"]
    zsh_completion.install Dir["share/zsh/site-functions/*"]
    fish_completion.install Dir["share/fish/vendor_completions.d/*"]
    man1.install Dir["share/man/man1/*.1"]
    man8.install Dir["share/man/man8/*.8"]
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ufop --version")
    assert_match "complete -F _ufop", shell_output("#{bin}/ufop completions bash")
  end
end
RUBY
}

if [[ -n "$OUT" ]]; then
  formula > "$OUT"
  echo "  + $(basename "$OUT")"
else
  formula
fi
