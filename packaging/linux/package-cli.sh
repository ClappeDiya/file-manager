#!/usr/bin/env bash
# package-cli.sh — package the `ufop` CLI (and `ufop-server` when built)
# with shell completions and man pages, for one Rust target.
#
# Produces, in --out:
#   ufop-<version>-<target>.tar.gz   (Linux/macOS; .zip for Windows targets)
#     ufop-<version>-<target>/
#       bin/ufop[.exe]  bin/ufop-server[.exe]
#       share/bash-completion/completions/ufop       (+ ufop-server)
#       share/zsh/site-functions/_ufop
#       share/fish/vendor_completions.d/ufop.fish
#       share/powershell/_ufop.ps1   share/elvish/ufop.elv
#       share/man/man1/ufop*.1  share/man/man8/ufop-server*.8
#       lib/systemd/system/ufop-server.service       (Linux, with ufop-server)
#       install.sh  LICENSE  README.txt
#   ufop_<version>_<arch>.deb        (with --deb, Linux targets; dpkg-deb)
#
# Completions and man pages are generated by running a binary for THIS
# machine (--gen-bin, default: bin/ufop when the target is the host), so
# cross-compiled packages get them too.
#
# Usage:
#   packaging/linux/package-cli.sh --version 1.2.0 --target x86_64-unknown-linux-gnu \
#       --bin-dir cli/target/x86_64-unknown-linux-gnu/release [--server-bin PATH] \
#       [--gen-bin PATH] [--gen-server-bin PATH] [--out release-artifacts/v1.2.0] [--deb] [--dry-run]

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

VERSION=""
TARGET=""
BIN_DIR=""
SERVER_BIN=""
GEN_BIN=""
GEN_SERVER_BIN=""
OUT="."
DEB=false
DRY_RUN=false

usage() { sed -n '2,28p' "$0" | sed 's/^# \{0,1\}//'; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --version) VERSION="$2"; shift 2 ;;
    --target) TARGET="$2"; shift 2 ;;
    --bin-dir) BIN_DIR="$2"; shift 2 ;;
    --server-bin) SERVER_BIN="$2"; shift 2 ;;
    --gen-bin) GEN_BIN="$2"; shift 2 ;;
    --gen-server-bin) GEN_SERVER_BIN="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --deb) DEB=true; shift ;;
    --dry-run) DRY_RUN=true; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "package-cli: unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[[ -n "$VERSION" && -n "$TARGET" && -n "$BIN_DIR" ]] || { echo "package-cli: --version, --target and --bin-dir are required" >&2; exit 2; }

EXE=""
ARCHIVE=tar.gz
case "$TARGET" in
  *windows*) EXE=".exe"; ARCHIVE=zip ;;
esac
case "$TARGET" in
  x86_64-*) DEB_ARCH=amd64 ;;
  aarch64-*) DEB_ARCH=arm64 ;;
  universal-*) DEB_ARCH=all ;;
  *) DEB_ARCH="${TARGET%%-*}" ;;
esac

UFOP="$BIN_DIR/ufop$EXE"
[[ -n "$SERVER_BIN" ]] || SERVER_BIN="$BIN_DIR/ufop-server$EXE"
GEN_BIN="${GEN_BIN:-$UFOP}"
GEN_SERVER_BIN="${GEN_SERVER_BIN:-$SERVER_BIN}"
NAME="ufop-${VERSION}-${TARGET}"
STAGE_DIR="$OUT/.stage-$NAME"
PKG="$STAGE_DIR/$NAME"

if [[ "$DRY_RUN" == true ]]; then
  echo "package-cli plan:"
  echo "  binaries:     $UFOP$([[ -f "$SERVER_BIN" ]] && echo " $SERVER_BIN" || echo " (ufop-server: $SERVER_BIN, included when present)")"
  echo "  completions:  bash zsh fish powershell elvish (generated with $GEN_BIN)"
  echo "  man pages:    $GEN_BIN man --out …"
  echo "  archive:      $OUT/$NAME.$ARCHIVE"
  if [[ "$DEB" == true && "$TARGET" == *linux* ]]; then
    echo "  deb:          $OUT/ufop_${VERSION}_${DEB_ARCH}.deb (/usr/bin, /usr/share/bash-completion/completions, /usr/share/zsh/vendor-completions, /usr/share/fish/vendor_completions.d, /usr/share/man/man1)"
  fi
  exit 0
fi

[[ -x "$UFOP" ]] || { echo "package-cli: $UFOP not found (build the CLI first)" >&2; exit 1; }
[[ -x "$GEN_BIN" ]] || { echo "package-cli: $GEN_BIN cannot run here; pass --gen-bin with a ufop built for this machine" >&2; exit 1; }
HAVE_SERVER=false
[[ -x "$SERVER_BIN" ]] && HAVE_SERVER=true

rm -rf "$STAGE_DIR"
mkdir -p "$PKG/bin" "$PKG/share/bash-completion/completions" "$PKG/share/zsh/site-functions" \
  "$PKG/share/fish/vendor_completions.d" "$PKG/share/powershell" "$PKG/share/elvish" "$PKG/share/man/man1" "$PKG/share/man/man8"

cp -p "$UFOP" "$PKG/bin/"
bins=(ufop)
gens=("$GEN_BIN")
if [[ "$HAVE_SERVER" == true ]]; then
  cp -p "$SERVER_BIN" "$PKG/bin/"
  if [[ -x "$GEN_SERVER_BIN" ]]; then
    bins+=(ufop-server)
    gens+=("$GEN_SERVER_BIN")
  else
    echo "package-cli: note: $GEN_SERVER_BIN cannot run here; ufop-server completions skipped" >&2
  fi
fi

for i in "${!bins[@]}"; do
  b="${bins[$i]}"
  g="${gens[$i]}"
  "$g" completions bash > "$PKG/share/bash-completion/completions/$b"
  "$g" completions zsh > "$PKG/share/zsh/site-functions/_$b"
  "$g" completions fish > "$PKG/share/fish/vendor_completions.d/$b.fish"
  "$g" completions powershell > "$PKG/share/powershell/_$b.ps1"
  "$g" completions elvish > "$PKG/share/elvish/$b.elv"
  # ufop: section 1; ufop-server: section 8 (daemons).
  if [[ "$b" == ufop-server ]]; then
    "$g" man --out "$PKG/share/man/man8" 2>/dev/null
  else
    "$g" man --out "$PKG/share/man/man1" 2>/dev/null
  fi
done
rmdir "$PKG/share/man/man8" 2>/dev/null || true

if [[ "$TARGET" == *linux* && "$HAVE_SERVER" == true ]]; then
  mkdir -p "$PKG/lib/systemd/system"
  cp "$ROOT/packaging/linux/ufop-server.service" "$PKG/lib/systemd/system/"
fi
cp "$ROOT/LICENSE" "$PKG/LICENSE"
cat > "$PKG/README.txt" <<EOF
UFOP command-line tools ${VERSION} (${TARGET})

  bin/ufop          the CLI (backups, copy, sync, transfer, server control)
  bin/ufop-server   the headless backup server (when included)
  share/            shell completions (bash, zsh, fish, PowerShell, Elvish) and man pages

Install under /usr/local (or PREFIX=...):  sudo ./install.sh
Verify a download first:                    https://github.com/ClappeDiya/file-manager (scripts/verify-release.sh)
EOF
cat > "$PKG/install.sh" <<'EOF'
#!/usr/bin/env bash
# Install the UFOP CLI with its completions and man pages.
#   sudo ./install.sh                 # /usr/local
#   PREFIX=$HOME/.local ./install.sh  # per user
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PREFIX="${PREFIX:-/usr/local}"
install -d "$PREFIX/bin"
for b in "$here"/bin/*; do install -m 0755 "$b" "$PREFIX/bin/"; done
for d in bash-completion/completions zsh/site-functions fish/vendor_completions.d; do
  if compgen -G "$here/share/$d/*" >/dev/null; then
    install -d "$PREFIX/share/$d"
    install -m 0644 "$here"/share/"$d"/* "$PREFIX/share/$d/"
  fi
done
for sec in 1 8; do
  if compgen -G "$here/share/man/man$sec/*.$sec" >/dev/null; then
    install -d "$PREFIX/share/man/man$sec"
    install -m 0644 "$here"/share/man/man"$sec"/*."$sec" "$PREFIX/share/man/man$sec/"
  fi
done
echo "Installed to $PREFIX (open a new shell for completions; PowerShell/Elvish scripts are in $here/share)."
EOF
chmod +x "$PKG/install.sh"

mkdir -p "$OUT"
if [[ "$ARCHIVE" == zip ]]; then
  python3 - "$STAGE_DIR" "$NAME" "$OUT/$NAME.zip" <<'PY'
import os, sys, zipfile
stage, name, out = sys.argv[1], sys.argv[2], sys.argv[3]
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for root, _, files in os.walk(os.path.join(stage, name)):
        for f in sorted(files):
            p = os.path.join(root, f)
            z.write(p, os.path.relpath(p, stage))
PY
else
  tar -C "$STAGE_DIR" -czf "$OUT/$NAME.tar.gz" "$NAME"
fi
echo "  + $NAME.$ARCHIVE"

if [[ "$DEB" == true && "$TARGET" == *linux* ]]; then
  command -v dpkg-deb >/dev/null 2>&1 || { echo "package-cli: dpkg-deb not found; skipping the .deb" >&2; DEB=false; }
fi
if [[ "$DEB" == true && "$TARGET" == *linux* ]]; then
  D="$STAGE_DIR/deb"
  mkdir -p "$D/DEBIAN" "$D/usr/bin" "$D/usr/share/bash-completion/completions" "$D/usr/share/zsh/vendor-completions" \
    "$D/usr/share/fish/vendor_completions.d" "$D/usr/share/man/man1" "$D/usr/share/man/man8" "$D/usr/share/doc/ufop"
  install -m 0755 "$PKG"/bin/* "$D/usr/bin/"
  install -m 0644 "$PKG"/share/bash-completion/completions/* "$D/usr/share/bash-completion/completions/"
  install -m 0644 "$PKG"/share/zsh/site-functions/* "$D/usr/share/zsh/vendor-completions/"
  install -m 0644 "$PKG"/share/fish/vendor_completions.d/* "$D/usr/share/fish/vendor_completions.d/"
  for m in "$PKG"/share/man/man1/*.1 "$PKG"/share/man/man8/*.8; do
    [[ -f "$m" ]] || continue
    sec="${m##*.}"
    gzip -9n < "$m" > "$D/usr/share/man/man$sec/$(basename "$m").gz"
  done
  rmdir "$D/usr/share/man/man8" 2>/dev/null || true
  cp "$ROOT/LICENSE" "$D/usr/share/doc/ufop/copyright"
  if [[ -d "$PKG/lib/systemd/system" ]]; then
    mkdir -p "$D/lib/systemd/system"
    install -m 0644 "$PKG"/lib/systemd/system/* "$D/lib/systemd/system/"
  fi
  size_kb="$(du -sk "$D/usr" | cut -f1)"
  cat > "$D/DEBIAN/control" <<EOF
Package: ufop
Version: ${VERSION}
Architecture: ${DEB_ARCH}
Maintainer: UFOP Team <noreply@clappe.com>
Installed-Size: ${size_kb}
Depends: libc6
Section: utils
Priority: optional
Homepage: https://github.com/ClappeDiya/file-manager
Description: UFOP command-line tools
 Versioned, deduplicated, encrypted backups, Robocopy-compatible copy,
 sync and transfers from the command line, and the headless backup server,
 with bash, zsh and fish completions and man pages.
EOF
  dpkg-deb --root-owner-group --build "$D" "$OUT/ufop_${VERSION}_${DEB_ARCH}.deb" >/dev/null
  echo "  + ufop_${VERSION}_${DEB_ARCH}.deb"
fi
rm -rf "$STAGE_DIR"
